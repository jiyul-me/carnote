def _ym(mo):
    """개월 수를 햇수로 — 42 → '3년 6개월', 24 → '2년'."""
    y, m = divmod(mo, 12)
    if not y:
        return f"{m}개월"
    return f"{y}년" if not m else f"{y}년 {m}개월"


def _interval(c, pid):
    """표·문장용 주기 — 1년이 넘는 기간만 있는 항목은 햇수를 덧붙인다('24개월(2년)마다', '12개월마다'는 그대로)."""
    p = c.part(pid)
    t = c.interval_text(pid)
    mo = p.get("intervalMonths")
    if mo and not p.get("intervalKm") and mo > 12 and t.endswith("마다"):
        t = t[:-2] + f"({_ym(mo)})마다"
    return t


def _when(c, pid):
    """'…에'/'…마다' — interval_text 끝말에 맞춰 조사를 붙인다."""
    t = _interval(c, pid)
    return t + "에" if t.endswith("때") else t


