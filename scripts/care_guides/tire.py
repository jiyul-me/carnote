def _when(c, pid):
    """문장용 '…에'/'…마다' — interval_text 끝말에 맞춰 조사를 붙인다."""
    t = c.interval_text(pid)
    return t + "에" if t.endswith("때") else t


def _note_age_years(c):
    """parts.json tire.note의 '제조 후 N년' — 수첩 안내 문구와 같은 햇수. 없으면 None."""
    m = re.search(r"제조 후\s*(\d+)\s*년", c.part("tire").get("note") or "")
    return int(m.group(1)) if m else None


