        ["차일지 기본 주기", B.esc(_cycle(c, "cabin-filter")), B.esc(_cycle(c, "air-filter"))],
        ["해당하는 차", B.esc(_who(cabin)), B.esc(_who(air))],
        ["막히면", "바람이 약해질 수 있어요", "가속이 둔해질 수 있어요"],
