# 설명서 비교용 값 — 글에 숫자로 쓰지 않고, 차일지 기본값이 더 짧은지 고르는 데만 쓴다.
# 2026-10 첫 조사 값(현대 NE1 2025·기아 MQ4 2021 '15,000km마다', 현대 CE1 2025 '12개월마다').
# 출처 정리 때 다시 확인된 건 현대 설명서의 '12개월마다'(여러 차종)와 일부 점검표의 '15,000km' 표기까지라,
# 글은 '이보다 긴 주기를 적은 차종도 있다' 수준으로만 쓴다.
MANUAL_CABIN_KM = 15000
MANUAL_CABIN_MONTHS = 12

FUEL = {"gasoline": "가솔린", "diesel": "디젤", "lpg": "LPG", "hybrid": "하이브리드", "ev": "전기차"}


def _cycle(c, pid):
    """표의 주기 칸 — '10,000km 또는 6개월'·'40,000km마다'."""
    return c.interval_text(pid).replace(" 중 먼저 오는 때", "")


def _who(p):
    """표의 '해당하는 차' 칸 — appliesTo로."""
    applies = p["appliesTo"]
    if set(applies) >= set(FUEL):
        return "모든 차(전기차 포함)"
    names = "·".join(v for k, v in FUEL.items() if k in applies)
    return f"엔진이 있는 차({names})" if "ev" not in applies else names


def _oil_ratio(c):
    """에어클리너 주기가 엔진오일 주기의 몇 배인지 — 딱 나눠떨어질 때만 문장으로."""
    air, oil = c.part("air-filter").get("intervalKm"), c.part("engine-oil").get("intervalKm")
    if air and oil and air % oil == 0 and air // oil > 1:
        return f"차일지 기본값으로 보면 에어클리너는 엔진오일을 {air // oil}번 바꿀 때 1번꼴로 바꿔요. "
    return ""


def _cabin_shorter(c):
    """차일지 에어컨 필터 기본값이 확인한 설명서 주기보다 짧은지."""
    p = c.part("cabin-filter")
    km, mo = p.get("intervalKm"), p.get("intervalMonths")
    return (km is None or km < MANUAL_CABIN_KM) and (mo is None or mo < MANUAL_CABIN_MONTHS)


def _cabin_vs_manual(c):
    """차일지 에어컨 필터 기본값과 확인한 설명서 주기의 관계 — 숫자 없이."""
    if _cabin_shorter(c):
        return ("에어컨 필터는 차일지가 짧게 잡은 편이에요. 제조사 설명서에는 이보다 긴 주기를 적은 차종도 있고, "
                "그 숫자도 차종마다 달라요.")
    return ("에어컨 필터 주기는 제조사 설명서끼리도 차종마다 달라요. "
            "차일지 기본값이 내 차 설명서보다 길 수도 있으니 꼭 견줘 보세요.")


def _ev_text(c):
    """전기차 — 에어컨 필터는 있고 에어클리너는 없다(appliesTo 기준)."""
    cabin, air = c.part("cabin-filter"), c.part("air-filter")
    if "ev" in cabin["appliesTo"] and "ev" not in air["appliesTo"]:
        return (f"<p>전기차는 엔진이 없어서 에어클리너가 없어요. 에어컨 필터는 있으니 똑같이 챙겨야 해요. "
                f"전기차만의 관리 포인트는 {c.link_care('ev-care', '전기차 관리 글')}에 정리했어요.</p>")
    return ""


