def _fuel_filter(c):
    """연료필터 — 다른 필터라 짧게, 정비소에 맡기라고. 주기·기본 꺼짐은 parts.json."""
    B = c.B
    off = [p for p in (c.part("fuel-filter-gasoline"), c.part("fuel-filter-lpg")) if not p.get("defaultEnabled", True)]
    out = (f"<p>공기 말고 연료를 거르는 필터도 하나 있어요. 연료 속 이물질을 걸러 내는 연료필터예요. 연료를 다루는 작업이라 "
           f"직접 손대지 말고 정비소에 맡기세요. 디젤차 연료필터의 차일지 기본 주기는 "
           f"{B.esc(c.interval_text('fuel-filter-diesel'))}예요. 자세한 건 {c.link_care('diesel-care', '디젤차 관리 글')}에 있어요.")
    if off:
        why = " ".join(FUEL_FILTER_OFF_WHY[f] for p in off for f in p["appliesTo"] if f in FUEL_FILTER_OFF_WHY)
        names = "·".join(f"'{B.esc(p['name'])}'" for p in off)
        out += (f" {why} 그래서 수첩에서는 {names} 항목을 기본으로 꺼 두었어요. "
                "설명서 정기 점검표에 연료필터 교체가 있을 때만 수첩에서 켜세요.")
    return out + "</p>"


